#!/usr/bin/env node
/*
 * Reads .env, writes js/config.js (window.SITE_CONFIG for runtime use),
 * and patches the SITE_URL domain into robots.txt, sitemap.xml, and the
 * canonical/OG/Twitter meta tags in every HTML page.
 *
 * Usage: node scripts/generate-config.js
 */
"use strict";

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const ENV_PATH = path.join(ROOT, ".env");
const CONFIG_PATH = path.join(ROOT, "js", "config.js");
const DEFAULT_SITE_URL = "https://www.xifona.app";

function parseEnv(text) {
  const env = {};
  text.split(/\r?\n/).forEach(function (line) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) return;
    const eq = trimmed.indexOf("=");
    if (eq === -1) return;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    env[key] = value;
  });
  return env;
}

function main() {
  if (!fs.existsSync(ENV_PATH)) {
    console.error(".env not found at " + ENV_PATH);
    process.exit(1);
  }

  const env = parseEnv(fs.readFileSync(ENV_PATH, "utf8"));
  const siteUrl = (env.SITE_URL || DEFAULT_SITE_URL).replace(/\/+$/, "");

  // 1. Write js/config.js
  const configBody =
    "// Generated by scripts/generate-config.js from .env — do not edit by hand.\n" +
    "window.SITE_CONFIG = " + JSON.stringify(env, null, 2) + ";\n";
  fs.writeFileSync(CONFIG_PATH, configBody);
  console.log("Wrote " + path.relative(ROOT, CONFIG_PATH));

  // 2. Patch SITE_URL into robots.txt, sitemap.xml, and HTML meta tags.
  const filesToPatch = fs
    .readdirSync(ROOT)
    .filter(function (f) { return f.endsWith(".html"); })
    .concat(["robots.txt", "sitemap.xml"]);

  let patchedCount = 0;
  filesToPatch.forEach(function (file) {
    const filePath = path.join(ROOT, file);
    if (!fs.existsSync(filePath)) return;
    const original = fs.readFileSync(filePath, "utf8");
    const updated = original.split(DEFAULT_SITE_URL).join(siteUrl);
    if (updated !== original) {
      fs.writeFileSync(filePath, updated);
      patchedCount++;
    }
  });
  console.log(
    "Patched domain (" + siteUrl + ") into " + patchedCount + " file(s)."
  );

  console.log("Done. Reload the site to see updated links/text.");
}

main();
